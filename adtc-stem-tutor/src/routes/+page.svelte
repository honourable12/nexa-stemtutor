  // Gas particle initializer
  function initGasParticles(count: number, temp: number, vol: number) {
    if (!canvasEl) return;
    const width = (vol / 100) * 280 + 80; // min width 80px, max 360px
    const height = 210;
    particles = [];
    
    // Scale speed to T (v_rms is proportional to sqrt(T))
    const speedMultiplier = Math.sqrt(temp) * 0.18;

    for (let i = 0; i < count; i++) {
      const radius = 5;
      const x = radius + Math.random() * (width - 2 * radius);
      const y = radius + Math.random() * (height - 2 * radius);
      const angle = Math.random() * Math.PI * 2;
      const speed = (0.7 + Math.random() * 0.6) * speedMultiplier;
      
      particles.push({
        x,
        y,
        vx: Math.cos(angle) * speed,
        vy: Math.sin(angle) * speed,
        radius,
        // HSL temperature color styling (blue = cold, orange/red = hot)
        color: `hsl(${(1 - (temp - 100) / 500) * 200}, 85%, 60%)`
      });
    }
  }

  // Animation Loop: Gas Simulation Solver
  function animateGas(timestamp: number) {
    if (!canvasEl) return;
    const ctx = canvasEl.getContext("2d");
    if (!ctx) return;

    const width = (gasVolume / 100) * 280 + 80;
    const height = 210;

    // Clear canvas
    ctx.clearRect(0, 0, 400, 250);

    // Draw container boundaries
    ctx.strokeStyle = "#1e293b";
    ctx.lineWidth = 3;
    ctx.fillStyle = "rgba(15, 23, 42, 0.4)";
    ctx.strokeRect(0, 0, width, height);
    ctx.fillRect(0, 0, width, height);

    // Speed target based on current temperature
    const targetSpeedBase = Math.sqrt(gasTemperature) * 0.18;

    particles.forEach((p) => {
      // Slowly adjust speed of particle to match new temperature setting
      const speed = Math.sqrt(p.vx * p.vx + p.vy * p.vy);
      if (speed > 0 && Math.abs(speed - targetSpeedBase) > 0.05) {
        const ratio = targetSpeedBase / speed;
        p.vx *= ratio;
        p.vy *= ratio;
      }

      p.x += p.vx;
      p.y += p.vy;

      // Collide walls
      if (p.x - p.radius < 0) {
        p.x = p.radius;
        p.vx = -p.vx;
        momentumTransferred += 2 * Math.abs(p.vx);
      } else if (p.x + p.radius > width) {
        p.x = width - p.radius;
        p.vx = -p.vx;
        momentumTransferred += 2 * Math.abs(p.vx);
      }

      if (p.y - p.radius < 0) {
        p.y = p.radius;
        p.vy = -p.vy;
        momentumTransferred += 2 * Math.abs(p.vy);
      } else if (p.y + p.radius > height) {
        p.y = height - p.radius;
        p.vy = -p.vy;
        momentumTransferred += 2 * Math.abs(p.vy);
      }

      // Draw molecule
      ctx.beginPath();
      ctx.arc(p.x, p.y, p.radius, 0, Math.PI * 2);
      ctx.fillStyle = p.color;
      // Add subtle glow matching particle temperature color
      ctx.shadowBlur = 4;
      ctx.shadowColor = p.color;
      ctx.fill();
      ctx.shadowBlur = 0;
    });

    // Particle-to-particle simple elastic collisions
    for (let i = 0; i < particles.length; i++) {
      for (let j = i + 1; j < particles.length; j++) {
        const p1 = particles[i];
        const p2 = particles[j];
        const dx = p2.x - p1.x;
        const dy = p2.y - p1.y;
        const dist = Math.sqrt(dx * dx + dy * dy);
        const minDist = p1.radius + p2.radius;

        if (dist < minDist) {
          const overlap = minDist - dist;
          const nx = dx / dist;
          const ny = dy / dist;

          // Resolve overlap
          p1.x -= nx * overlap * 0.5;
          p1.y -= ny * overlap * 0.5;
          p2.x += nx * overlap * 0.5;
          p2.y += ny * overlap * 0.5;

          // Swap normal velocities
          const kx = p1.vx - p2.vx;
          const ky = p1.vy - p2.vy;
          const normalVel = nx * kx + ny * ky;
          if (normalVel > 0) {
            p1.vx -= nx * normalVel;
            p1.vy -= ny * normalVel;
            p2.vx += nx * normalVel;
            p2.vy += ny * normalVel;
          }
        }
      }
    }

    // Accumulate pressure metric
    collisionTimeElapsed += 1 / 60;
    if (collisionTimeElapsed >= 0.5) {
      // P = (Sum(2 * m * v_normal)) / (time * perimeter)
      const perimeter = 2 * (width + height);
      gasPressureMeasured = (momentumTransferred / (collisionTimeElapsed * perimeter)) * 14;
      momentumTransferred = 0;
      collisionTimeElapsed = 0;
    }

    if (activeSandboxTab === "gas") {
      requestAnimationFrame(animateGas);
    }
  }

  // Svelte 5 Effect to trigger gas simulation
  $effect(() => {
    if (activeSandboxTab === "gas" && canvasEl) {
      initGasParticles(gasParticlesCount, gasTemperature, gasVolume);
      let frame = requestAnimationFrame(animateGas);
      return () => cancelAnimationFrame(frame);
    }
  });

  // Reinit particles when quantity or volume slider changes
  $effect(() => {
    if (activeSandboxTab === "gas" && canvasEl) {
      initGasParticles(gasParticlesCount, gasTemperature, gasVolume);
    }
  });
</script>

