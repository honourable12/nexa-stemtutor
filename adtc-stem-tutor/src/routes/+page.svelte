  // Animation Loop: Pendulum physics Solver
  function animatePendulum(timestamp: number) {
    if (!lastTime) lastTime = timestamp;
    let dt = (timestamp - lastTime) / 1000;
    if (dt > 0.1) dt = 0.1; // cap frame lag
    lastTime = timestamp;

    if (pendulumActive) {
      // Angular acceleration: alpha = -(g / L) * sin(theta)
      const alpha = -(pendulumGravity / pendulumLength) * Math.sin(theta);
      omega += alpha * dt;
      theta += omega * dt;
      pendulumTime += dt;
    }

    if (activeSandboxTab === "pendulum") {
      requestAnimationFrame(animatePendulum);
    }
  }

  // Svelte 5 Effect to toggle Pendulum physics solver
  $effect(() => {
    if (activeSandboxTab === "pendulum") {
      lastTime = 0;
      let frame = requestAnimationFrame(animatePendulum);
      return () => cancelAnimationFrame(frame);
    }
  });

