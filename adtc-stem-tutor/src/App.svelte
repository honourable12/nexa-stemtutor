        <span>Simulator Terminal Output</span>
      </div>
      <div style="display: flex; align-items: center; gap: 0.75rem;">
        {#if chatHistory.length > 0}
          <button 
            on:click={clearHistory} 
            disabled={isGenerating} 
            class="btn-clear-console"
            title="Clear conversation history to free RAM/context"
          >
            🧹 Clear Context
          </button>
        {/if}
        {#if isGenerating}
          <span class="loader-pulse">⚡ Stream Active (Computing...)</span>
        {:else}
          <span class="status-ready">✓ System Idle</span>
        {/if}
      </div>
    </div>
    <div id="terminal-view" class="terminal-view">
      {@html formattedConsole}
    </div>
  </section>

  <!-- Interaction Tray -->
  <footer class="interaction-tray">
    <input 
      type="text" 
      bind:value={studentInput} 
      placeholder="Ask a custom science question (e.g., Explain the physics of centrifugal acceleration)..." 
      disabled={isGenerating}
      on:keydown={(e) => e.key === 'Enter' && launchSimulation(studentInput, "Custom Query")}
      class="student-input"
    />
    <button 
      on:click={() => launchSimulation(studentInput, "Custom Query")} 
      disabled={isGenerating || !studentInput.trim()}
      class="run-btn"
    >
      Run Experiment
    </button>
  </footer>
</main>

