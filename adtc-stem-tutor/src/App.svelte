<script lang="ts">
  import { invoke } from '@tauri-apps/api/core';
  import { listen } from '@tauri-apps/api/event';
  import { onMount } from 'svelte';

  let studentInput = '';
  let terminalBuffer = 'Select a lab module from the shortcuts or input a custom science experiment to begin...';
  let isGenerating = false;
  let isFirstToken = false;
  let activeModule = '';

  interface ChatMessage {
    role: "user" | "assistant";
    content: string;
  }
  let chatHistory: ChatMessage[] = [];

  function compileChatMLPrompt(newQuery: string): string {
    const systemPrompt = "You are a Localized STEM Virtual Lab Tutor. Explain concepts step-by-step. Detail all mathematical derivations, physical laws, and chemical reactions clearly. If asked to translate, support multilingual outputs (e.g., Swahili, French) flawlessly.";
    const lastTurnsMessages = chatHistory.slice(-6);
    let prompt = `<|im_start|>system\n${systemPrompt}<|im_end|>\n`;
    for (const msg of lastTurnsMessages) {
      prompt += `<|im_start|>${msg.role}\n${msg.content}<|im_end|>\n`;
    }
    prompt += `<|im_start|>user\n${newQuery}<|im_end|>\n<|im_start|>assistant\n`;
    return prompt;
  }

  function clearHistory() {
    chatHistory = [];
    terminalBuffer = 'Select a lab module from the shortcuts or input a custom science experiment to begin...';
  }

  $: formattedConsole = formatConsoleForAppSvelte(chatHistory, terminalBuffer);
  
  function formatConsoleForAppSvelte(history: ChatMessage[], buffer: string): string {
    let html = "";
    for (const msg of history) {
      if (msg.role === "user") {
        const escapedContent = msg.content
          .replace(/&/g, "&amp;")
          .replace(/</g, "&lt;")
          .replace(/>/g, "&gt;");
        html += `<div class="terminal-user-query"><span class="cmd-prompt">&gt; Student:</span> <span class="query-text">${escapedContent}</span></div>`;
      } else if (msg.role === "assistant") {
        html += `<div class="terminal-assistant-response">${msg.content}</div>`;
      }
    }
    if (buffer) {
      html += `<div class="terminal-current-stream">${buffer}</div>`;
    }
    return html;
  }

  // Curated interactive lab shortcuts for offline users
  const labShortcuts = [
    { 
      name: "🧲 Electromagnetism", 
      prompt: "Explain the magnetic field lines generated by a solenoid step-by-step.",
      desc: "Solenoid flux lines, right-hand rule, and core permeability."
    },
    { 
      name: "📐 Pendulum Period", 
      prompt: "Write the mathematical derivation for a simple pendulum's period under gravity.",
      desc: "Small-angle approximation, torque equations, and string length."
    },
    { 
      name: "🧪 Ideal Gas Law", 
      prompt: "Explain how changing temperature affects volume using molecular kinetic theory.",
      desc: "Gas constants, elastic collisions, and thermal expansion dynamics."
    }
  ];

  onMount(async () => {
    // Intercept native incoming tokens streamed directly from the Rust backend thread loop
    await listen<{ token: string }>('adtc-token-stream', (event) => {
      if (isFirstToken) {
        terminalBuffer = ""; // Flush initialization strings instantly upon first token arrival
        isFirstToken = false;
      }
      terminalBuffer += event.payload.token;

      // Smooth scroll to the bottom of the simulator output terminal
      const consoleView = document.getElementById('terminal-view');
      if (consoleView) {
        consoleView.scrollTop = consoleView.scrollHeight;
      }
    });
  });

  async function launchSimulation(queryText: string, label: string = "Custom Query") {
    if (!queryText.trim() || isGenerating) return;
    
    const compiledPrompt = compileChatMLPrompt(queryText);
    studentInput = '';
    chatHistory.push({ role: "user", content: queryText });

    isGenerating = true;
    isFirstToken = true;
    activeModule = label;
    terminalBuffer = `[SYSTEM]: Connecting to offline GGML backend...\n` +
                     `[SYSTEM]: Pinned Core: 4 Threads (-t 4)\n` +
                     `[SYSTEM]: Context Cache: FP16 active (Strict 3,072 max tokens)\n` +
                     `[SYSTEM]: Loading local Qwen3.5 ~2B model parameters...\n` +
                     `[SYSTEM]: Pre-loading context arrays for: "${queryText}"...\n\n` +
                     `[SYSTEM]: Running inference... (Calculations started)\n\n`;
    
    try {
      await invoke('stream_stem_tutor_inference', { studentPrompt: compiledPrompt });
      chatHistory.push({ role: 'assistant', content: terminalBuffer });
      terminalBuffer += `\n\n[SYSTEM]: Inference complete. CPU resources released back to host OS.`;
    } catch (err) {
      terminalBuffer += `\n\n[CRITICAL ERROR]: ${err}`;
    } finally {
      isGenerating = false;
      isFirstToken = false;
    }
  }
</script>

